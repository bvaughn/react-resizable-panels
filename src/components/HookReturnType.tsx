import { DocsSection, SectionHeader } from "react-lib-tools";
import { Link } from "./Link";
import { TypeFields } from "./TypeFields";
import type { ModelTypeMetadata } from "./workspace/ModelType";

// Imperative APIs that a hook's return type can include (e.g. "ParentWorkspace" includes "WorkspaceImperativeHandle")
const IMPERATIVE_API_PATHS = {
  GridImperativeHandle: "/imperative-api/grid",
  GroupImperativeHandle: "/imperative-api/group",
  PanelImperativeHandle: "/imperative-api/panel",
  WorkspaceImperativeHandle: "/imperative-api/workspace"
} as const;

/**
 * Documents the type a hook returns (generated by `compile:types` from the type's source),
 * so that hook pages don't have to describe its fields by hand.
 */
export function HookReturnType({ json }: { json: ModelTypeMetadata }) {
  return (
    <>
      <SectionHeader>{json.name}</SectionHeader>
      <DocsSection sections={json.description} />
      {json.extends?.map((typeName) => {
        const path =
          IMPERATIVE_API_PATHS[typeName as keyof typeof IMPERATIVE_API_PATHS];
        if (!path) {
          throw Error(`No docs page for "${typeName}" (see HookReturnType)`);
        }

        return (
          <div key={typeName}>
            It includes every method of the{" "}
            <Link to={path}>
              <code>{typeName}</code>
            </Link>{" "}
            (the imperative API), along with these values:
          </div>
        );
      })}
      <TypeFields json={json} />
    </>
  );
}
